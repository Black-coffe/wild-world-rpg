<?php

declare(strict_types=1);

namespace App\Services\Db;

/**
 * Исход условной записи ({@see ConditionalWriteService}) — три случая, а не `bool`
 * (ADR-181 §3): `bool` схлопывает «не хватило» и «строки нет» в один текст отказа,
 * а это ровно дефект F1 из аудита эксплойтов. `match` по этому enum без `default`
 * ловится phpstan level 9 — забытый исход красит статический анализ, а не молчит.
 */
enum WriteOutcome
{
    /** Предусловие выполнилось, строка изменена — вызывающий обязан выдавать. */
    case Applied;

    /** Строка есть, но предусловие не выполнено (не хватило / не тот статус) — честный отказ игроку. */
    case Refused;

    /** Строки нет вовсе — обычно дефект вызывающего кода, не игровая ситуация. */
    case Missing;
}
