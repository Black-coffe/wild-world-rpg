<?php

declare(strict_types=1);

namespace App\Services\Telegram;

/**
 * ADR-150 (чистка дублей) — канонический ряд «что дальше» под уведомлениями и результатами.
 *
 * 🔴 Что чиним. По 17 экранам был скопирован один и тот же «суп» из шести кнопок:
 * `🎮 Развлечения · 🧑‍🌾 Действия · 🎉 События` / `🎒 Инвентарь · 🛒 Магазин · 💊 Аптечка`.
 * Он появлялся под результатом добычи, наградой за квест, сообщением о голоде, окопом,
 * побегом из боя — везде одинаковый, ни разу не контекстный. Плюс экран «🎉 События» имел
 * кнопку «🎉 События» на себя же (self-ref).
 *
 * Смысл в супе был, пока нижнего меню не существовало как навигации: он заменял панель.
 * После ADR-150 ФИНАЛ панель есть всегда, и каждая кнопка супа — в один-два тапа от неё
 * («🎒 Инвентарь» → «🧑 Я», «🛒 Магазин»/«🎮 Развлечения» → «⚙️ Ещё», «🎉 События» → «🌍 Мир»).
 * Шесть кнопок под каждым уведомлением стали шумом, который прячет главное: что делать дальше.
 *
 * Остаётся ровно один ряд из двух сиблингов: **идти** и **действовать**. Контекстные кнопки
 * конкретного экрана (приглушить событие, выпить аптечку, вернуться к маякам) супом НЕ были и
 * остаются на своих местах — их сайты добавляют сами.
 *
 * Гейт — `BotMenuService::finalGridEnabled()`: пока нижняя панель не доехала до игрока, суп
 * остаётся его единственной навигацией и трогать его нельзя. OFF → каждый сайт рендерит легаси
 * byte-identical.
 */
final class NavKeyboards
{
    /** Панель уже есть у игрока → суп можно сворачивать. */
    public static function simplified(): bool
    {
        return BotMenuService::finalGridEnabled();
    }

    /**
     * Канонический ряд «что дальше»: идти в мир либо действовать на клетке.
     *
     * Урок [[feedback_march_interrupt_return_to_map]]: после прерывания игрок хочет вернуться
     * к движению, а не в список действий — поэтому «🧭 Идти» стоит первым.
     *
     * @return list<list<array{text: string, callback_data: string}>>
     */
    public static function whatNext(): array
    {
        return [
            [
                ['text' => '🧭 Идти',           'callback_data' => 'move'],
                ['text' => '🧑‍🌾 Действия 🛠️', 'callback_data' => 'characterActions'],
            ],
        ];
    }

    /**
     * `whatNext()` + собственные ряды экрана (кнопки, которые супом не были).
     *
     * @param list<list<array{text: string, callback_data: string}>> $extraRows
     * @return array{inline_keyboard: list<list<array{text: string, callback_data: string}>>}
     */
    public static function whatNextWith(array $extraRows = []): array
    {
        return ['inline_keyboard' => array_merge(self::whatNext(), $extraRows)];
    }
}
