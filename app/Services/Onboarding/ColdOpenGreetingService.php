<?php

declare(strict_types=1);

namespace App\Services\Onboarding;

use App\Services\GameSettings\GameSettingsReaderTrait;

/**
 * S4 (ROADMAP-RETENTION-10, ADR-139) — cold-open framing /start (спина-слайс 1b).
 *
 * Проблема (S1): 58% свежей когорты НЕ называют чара — первый экран /start (121 слово)
 * слишком плотный для немедленного bounce. Cold-open вариант — короткое, интригующее
 * вступление от лица Роби (постапок-тон), ведущее к единственному CTA «назвать героя».
 * Полярная звезда (слайс 1a) дальше показывает первую цель на карточке/карте.
 *
 * Гейт — ОТДЕЛЬНЫЙ суб-killswitch `onboarding.cold_open_v2.start_greeting` (default OFF →
 * dormant = легаси-приветствие 121 слово, byte-identical). Намеренно НЕ мастер-флаг
 * `onboarding.cold_open_v2.enabled` (он уже включён для полярной звезды): первое впечатление
 * — субъективная высокоставочная копия, ей нужен СВОЙ Tier-3 cold-smoke + одобрение копии
 * владельцем до экспозиции (П10: «обновление не ломает онбординг»).
 *
 * Текст в коде (не GameSettings: value_string=255 мал). Самодостаточен (media-off, ADR-020),
 * markdown-safe (парные `*`, ссылка `[..](..)`).
 */
class ColdOpenGreetingService
{
    use GameSettingsReaderTrait;

    /** Суб-killswitch 1b: показывать cold-open приветствие вместо легаси. Default OFF → dormant. */
    public function greetingEnabled(): bool
    {
        return $this->gsBool('onboarding.cold_open_v2.start_greeting', false);
    }

    /**
     * Cold-open приветствие новичку (постапок-тон Роби, ~3 коротких абзаца). Ведёт к CTA
     * «🤔 Задать имя персонажа» (кнопку добавляет StartCommand следом). Самодостаточно.
     */
    public function greeting(): string
    {
        return "🤖 Я — *Роби*, твой проводник. Ты очнулся на острове, где рухнула цивилизация: "
            . "кругом пустошь, а выжившие сами решают, как жить дальше.\n\n"
            . "Здесь всё — своими руками: разведка, добыча, крафт, своя база. Первые шаги пройдём "
            . "вместе, дальше пустошь — твоя.\n\n"
            . "Сначала назови героя — и в путь. Вопросы и стратегии — в "
            . "[общем чате](https://t.me/wild_world_info).";
    }

    // ── Слайс «Первые 3 минуты» (замер 2026-07-24) ───────────────────────────

    /**
     * Суб-killswitch «одно окно вместо пяти»: свести первый контакт к ОДНОМУ
     * содержательному сообщению, где первый CTA — шаг в мир, а имя — необязательно.
     * Default OFF → dormant (пять сообщений и CTA «Задать имя», byte-identical).
     *
     * Отдельный флаг, а не мастер `enabled` (тот уже включён с 2026-06-25 ради полярной
     * звезды): первое впечатление — высокоставочная копия, ей нужен свой Tier-3 cold-smoke
     * и одобрение копии владельцем до экспозиции (тот же принцип, что у `start_greeting`).
     */
    public function singleScreenEnabled(): bool
    {
        return $this->gsBool('onboarding.cold_open_v2.single_screen', false);
    }

    /**
     * Вступление для режима «одно окно»: то же, что {@see greeting()}, но БЕЗ призыва
     * назвать героя — в этом режиме первый CTA ведёт в мир, а имя добирается позже
     * (оно и так автоподставлено из username при создании персонажа).
     */
    public function greetingSingleScreen(): string
    {
        return "🤖 Я — *Роби*, твой проводник. Ты очнулся на острове, где рухнула цивилизация: "
            . "кругом пустошь, а выжившие сами решают, как жить дальше.\n\n"
            . "Здесь всё — своими руками: разведка, добыча, крафт, своя база. Первые шаги пройдём "
            . "вместе, дальше пустошь — твоя.";
    }

    /**
     * Замыкающий призыв: единственное обязательное действие — шаг в мир.
     * Имя названо необязательным явно, чтобы игрок не считал его воротами (замер
     * 2026-07-24: 60% свежей когорты уходили, не пройдя CTA «Задать имя»).
     */
    public function closingSingleScreen(): string
    {
        return "Жми «🧭 Сделать первый шаг» — покажу, куда идти. "
            . "Имя герою дашь когда захочешь, спешки нет.\n\n"
            . "Вопросы и стратегии — в [общем чате](https://t.me/wild_world_info).";
    }

    /**
     * Собрать первый экран из готовых кусков (вступление, паёк, радио-сигнал, встречающий,
     * замыкание). Пустые/отсутствующие секции выпадают — при выключенных пайке/сигнале/
     * встречающем экран остаётся связным, а не разваливается на пробелы.
     *
     * Pure — тестируется без БД и Telegram.
     *
     * @param list<string|null> $sections
     */
    public function composeWelcome(array $sections): string
    {
        $parts = [];
        foreach ($sections as $section) {
            if (! is_string($section)) {
                continue;
            }
            $trimmed = trim($section);
            if ($trimmed !== '') {
                $parts[] = $trimmed;
            }
        }

        return implode("\n\n", $parts);
    }

    /**
     * Влезает ли собранный экран в одно сообщение Telegram (лимит 4096 символов).
     * Порог с запасом: если контент разрастётся, StartCommand честно откатится на
     * раздельную отправку, а не потеряет сообщение целиком.
     */
    public function fitsSingleMessage(string $text): bool
    {
        return mb_strlen($text) <= 3900;
    }
}
