//Для реализации автоматической транслитерации поля slug из украинского на английский в CodeIgniter 4,
//ты можешь создать общий сервис или библиотеку, которая будет доступна в разных контроллерах.
//Этот сервис будет принимать строку (название категории, тега, статьи) и возвращать
//транслитерированную строку в соответствии с SEO требованиями.

namespace App\Libraries;

class Slugifier
{
    //Этот класс Slugifier включает метод transliterate, который транслитерирует украинский текст в латиницу, соответствующую требованиям SEO.
    public function transliterate($text)
    {
        $ukrainian = ['Є','І','Ї','Ґ','є','і','ї','ґ','А','Б','В','Г','Д','Е','Ж','З','И','Й','К','Л','М','Н','О','П','Р','С','Т','У','Ф','Х','Ц','Ч','Ш','Щ','Ь','Ю','Я','а','б','в','г','д','е','ж','з','и','й','к','л','м','н','о','п','р','с','т','у','ф','х','ц','ч','ш','щ','ь','ю','я',' '];
        $latin = ['Ye','I','Yi','G','ye','i','yi','g','A','B','V','H','D','E','Zh','Z','Y','Y','K','L','M','N','O','P','R','S','T','U','F','Kh','Ts','Ch','Sh','Shch','','Yu','Ya','a','b','v','h','d','e','zh','z','y','y','k','l','m','n','o','p','r','s','t','u','f','kh','ts','ch','sh','shch','','yu','ya','-'];
        $text = str_replace($ukrainian, $latin, $text);

        // Преобразование в нижний регистр и удаление нежелательных символов
        $text = strtolower($text);
        $text = preg_replace('/[^a-z0-9-]/', '-', $text) ?? '';
        $text = preg_replace('/-+/', '-', $text) ?? '';
        $text = trim($text, '-');

        return $text;
    }
}